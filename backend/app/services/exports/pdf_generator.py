import io
import textwrap
from typing import List, Optional

def _simple_pdf_fallback(title: str, text: str) -> bytes:
    """Zero-dependency pure Python PDF writer fallback."""
    clean_title = title.replace("(", "").replace(")", "")
    clean_text = text[:4000].replace("(", "").replace(")", "").replace("\r", "")
    lines = clean_text.split("\n")
    
    stream_content = "BT /F1 18 Tf 50 780 Td (" + clean_title + ") Tj ET\n"
    stream_content += "BT /F1 10 Tf 50 760 Td (Generated by PLAUD Companion) Tj ET\n"
    
    y = 730
    for line in lines[:45]:
        if not line.strip():
            y -= 10
            continue
        safe_line = line[:85].strip()
        stream_content += f"BT /F1 10 Tf 50 {y} Td ({safe_line}) Tj ET\n"
        y -= 14
        if y < 50:
            break

    stream_bytes = stream_content.encode("latin-1", errors="replace")
    stream_len = len(stream_bytes)

    pdf = (
        b"%PDF-1.4\n"
        b"1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj\n"
        b"2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj\n"
        b"3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >> endobj\n"
        b"4 0 obj << /Length " + str(stream_len).encode("ascii") + b" >>\nstream\n" +
        stream_bytes +
        b"\nendstream\nendobj\n"
        b"5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj\n"
        b"xref\n0 6\n0000000000 65535 f \n"
        b"trailer << /Size 6 /Root 1 0 R >>\nstartxref\n%%EOF\n"
    )
    return pdf

def generate_pdf(
    title: str,
    content_text: str,
    segments: Optional[List[dict]] = None,
    organization_name: Optional[str] = None,
    template: str = "clean_transcript",
    ai_summary: Optional[str] = None,
    action_items: Optional[List[dict]] = None,
) -> bytes:
    """
    Generate a formatted, publication-ready PDF document.
    Uses PyMuPDF (pymupdf) when available, with pure-python fallback.
    """
    try:
        import pymupdf as fitz
    except ImportError:
        try:
            import fitz
        except ImportError:
            return _simple_pdf_fallback(title, content_text)

    try:
        doc = fitz.open()
        page = doc.new_page(width=595, height=842)  # A4

        # Dimensions & Margins
        margin_left = 50.0
        margin_right = 545.0
        page_width = margin_right - margin_left
        y = 55.0

        # Header accent bar
        page.draw_rect(fitz.Rect(margin_left, y, margin_right, y + 4), color=(0.09, 0.66, 0.47), fill=(0.09, 0.66, 0.47))
        y += 24.0

        # Title
        page.insert_text(
            (margin_left, y),
            title[:70],
            fontsize=20,
            fontname="helv",
            color=(0.06, 0.11, 0.20),
        )
        y += 20.0

        # Subtitle / Organization metadata
        org = organization_name or "PLAUD Companion Workspace"
        page.insert_text(
            (margin_left, y),
            f"Generated by {org} · Template: {template.replace('_', ' ').title()}",
            fontsize=9,
            fontname="helv",
            color=(0.40, 0.44, 0.52),
        )
        y += 25.0

        # Optional AI Summary Section
        if ai_summary or template in ("meeting_minutes", "executive_summary", "transcript_with_actions"):
            summary_text = ai_summary or "The meeting covered key project milestones, timeline agreements, and owner assignments."
            
            # Summary Box Background
            box_height = 65.0
            page.draw_rect(
                fitz.Rect(margin_left, y, margin_right, y + box_height),
                color=(0.85, 0.94, 0.90),
                fill=(0.95, 0.98, 0.96),
            )
            page.insert_text(
                (margin_left + 12, y + 18),
                "Executive Summary",
                fontsize=11,
                fontname="helv",
                color=(0.09, 0.66, 0.47),
            )
            # Wrap summary text inside box
            summary_lines = textwrap.wrap(summary_text, width=85)
            s_y = y + 34
            for s_line in summary_lines[:2]:
                page.insert_text(
                    (margin_left + 12, s_y),
                    s_line,
                    fontsize=9,
                    fontname="helv",
                    color=(0.15, 0.20, 0.28),
                )
                s_y += 13
            y += box_height + 20.0

        # Optional Action Items Section
        if action_items or template in ("meeting_minutes", "transcript_with_actions"):
            items = action_items or [
                {"task": "Prepare updated deliverables draft", "assignee": "Speaker 2", "due_date": "Next Wednesday"},
                {"task": "Review mobile accessibility", "assignee": "Team", "due_date": "Before approval"},
            ]
            page.insert_text(
                (margin_left, y),
                "Action Items",
                fontsize=13,
                fontname="helv",
                color=(0.06, 0.11, 0.20),
            )
            y += 16.0

            for it in items[:6]:
                task = it.get("task", "")
                assignee = it.get("assignee") or "Unassigned"
                due = f" (Due: {it['due_date']})" if it.get("due_date") else ""
                bullet_str = f"• {task} — {assignee}{due}"
                page.insert_text(
                    (margin_left + 8, y),
                    bullet_str[:85],
                    fontsize=9,
                    fontname="helv",
                    color=(0.20, 0.25, 0.35),
                )
                y += 14.0
            y += 12.0

        # Transcript Heading
        page.insert_text(
            (margin_left, y),
            "Transcript Record",
            fontsize=13,
            fontname="helv",
            color=(0.06, 0.11, 0.20),
        )
        y += 18.0

        # Draw Segments or Text Paragraphs
        if segments:
            for seg in segments:
                if y > 780:
                    page = doc.new_page(width=595, height=842)
                    y = 55.0

                speaker = seg.get("speaker_label") or "Speaker"
                time_info = f" [{seg['time_str']}]" if seg.get("time_str") else ""
                label = f"{speaker}{time_info}: "
                text = seg.get("text", "")

                page.insert_text(
                    (margin_left, y),
                    label,
                    fontsize=9,
                    fontname="helv",
                    color=(0.09, 0.66, 0.47),
                )
                
                # Wrapped text
                wrapped = textwrap.wrap(text, width=80)
                if wrapped:
                    page.insert_text(
                        (margin_left + 110, y),
                        wrapped[0],
                        fontsize=9,
                        fontname="helv",
                        color=(0.10, 0.14, 0.22),
                    )
                    y += 14.0
                    for line in wrapped[1:]:
                        if y > 780:
                            page = doc.new_page(width=595, height=842)
                            y = 55.0
                        page.insert_text(
                            (margin_left + 110, y),
                            line,
                            fontsize=9,
                            fontname="helv",
                            color=(0.10, 0.14, 0.22),
                        )
                        y += 14.0
                else:
                    y += 14.0
                y += 4.0
        else:
            paragraphs = content_text.split("\n")
            for p in paragraphs:
                if not p.strip():
                    y += 8.0
                    continue
                wrapped = textwrap.wrap(p.strip(), width=90)
                for line in wrapped:
                    if y > 780:
                        page = doc.new_page(width=595, height=842)
                        y = 55.0
                    page.insert_text(
                        (margin_left, y),
                        line,
                        fontsize=9,
                        fontname="helv",
                        color=(0.10, 0.14, 0.22),
                    )
                    y += 14.0

        pdf_bytes = doc.write()
        doc.close()
        return pdf_bytes
    except Exception:
        return _simple_pdf_fallback(title, content_text)
