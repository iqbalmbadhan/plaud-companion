import io
import zipfile
import html
from typing import List, Optional

CONTENT_TYPES_XML = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>
  <Override PartName="/word/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.styles+xml"/>
</Types>"""

RELS_XML = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>
</Relationships>"""

WORD_RELS_XML = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>
</Relationships>"""

STYLES_XML = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:styles xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
  <w:docDefaults>
    <w:rPrDefault>
      <w:rPr>
        <w:rFonts w:ascii="Calibri" w:hAnsi="Calibri"/>
        <w:sz w:val="22"/>
        <w:color w:val="172033"/>
      </w:rPr>
    </w:rPrDefault>
  </w:docDefaults>
</w:styles>"""

def _escape(text: str) -> str:
    return html.escape(text or "")

def generate_docx(
    title: str,
    content_text: str,
    segments: Optional[List[dict]] = None,
    organization_name: Optional[str] = None,
    template: str = "clean_transcript",
    ai_summary: Optional[str] = None,
    action_items: Optional[List[dict]] = None,
) -> bytes:
    """Generate a formatted Microsoft Word DOCX file as bytes."""
    buffer = io.BytesIO()

    body_xml_parts: List[str] = []

    # Title
    body_xml_parts.append(
        f'<w:p><w:pPr><w:jc w:val="left"/><w:spacing w:after="160"/></w:pPr>'
        f'<w:r><w:rPr><w:b/><w:sz w:val="44"/><w:color w:val="101B33"/></w:rPr>'
        f'<w:t>{_escape(title)}</w:t></w:r></w:p>'
    )

    # Subtitle / Organization metadata
    org = organization_name or "PLAUD Companion Workspace"
    body_xml_parts.append(
        f'<w:p><w:pPr><w:spacing w:after="240"/></w:pPr>'
        f'<w:r><w:rPr><w:i/><w:color w:val="667085"/><w:sz w:val="20"/></w:rPr>'
        f'<w:t>Generated by {org} · Template: {_escape(template.replace("_", " ").title())}</w:t></w:r></w:p>'
    )

    # Optional AI Summary Section
    if ai_summary or template in ("meeting_minutes", "executive_summary", "transcript_with_actions"):
        summary_text = ai_summary or "The meeting covered key project milestones, timeline agreements, and owner assignments."
        body_xml_parts.append(
            f'<w:p><w:pPr><w:spacing w:before="240" w:after="120"/></w:pPr>'
            f'<w:r><w:rPr><w:b/><w:sz w:val="28"/><w:color w:val="18A879"/></w:rPr>'
            f'<w:t>Executive Summary</w:t></w:r></w:p>'
        )
        body_xml_parts.append(
            f'<w:p><w:pPr><w:spacing w:after="200"/></w:pPr>'
            f'<w:r><w:t>{_escape(summary_text)}</w:t></w:r></w:p>'
        )

    # Optional Action Items Section
    if action_items or template in ("meeting_minutes", "transcript_with_actions"):
        items = action_items or [
            {"task": "Prepare updated deliverables draft", "assignee": "Speaker 2", "due_date": "Next Wednesday"},
            {"task": "Review mobile accessibility", "assignee": "Team", "due_date": "Before approval"},
        ]
        body_xml_parts.append(
            f'<w:p><w:pPr><w:spacing w:before="240" w:after="120"/></w:pPr>'
            f'<w:r><w:rPr><w:b/><w:sz w:val="28"/><w:color w:val="18A879"/></w:rPr>'
            f'<w:t>Action Items</w:t></w:r></w:p>'
        )
        for item in items:
            task = item.get("task", "")
            assignee = item.get("assignee") or "Unassigned"
            due = f" (Due: {item['due_date']})" if item.get("due_date") else ""
            body_xml_parts.append(
                f'<w:p><w:pPr><w:spacing w:after="80"/></w:pPr>'
                f'<w:r><w:rPr><w:b/><w:color w:val="18A879"/></w:rPr><w:t>• </w:t></w:r>'
                f'<w:r><w:rPr><w:b/></w:rPr><w:t>{_escape(task)}</w:t></w:r>'
                f'<w:r><w:rPr><w:color w:val="667085"/></w:rPr><w:t> — {_escape(assignee)}{_escape(due)}</w:t></w:r></w:p>'
            )

    # Transcript Heading
    body_xml_parts.append(
        f'<w:p><w:pPr><w:spacing w:before="300" w:after="140"/></w:pPr>'
        f'<w:r><w:rPr><w:b/><w:sz w:val="28"/><w:color w:val="101B33"/></w:rPr>'
        f'<w:t>Transcript Record</w:t></w:r></w:p>'
    )

    # Body / Segments
    if segments:
        for seg in segments:
            speaker = seg.get("speaker_label") or "Speaker"
            time_str = f" [{seg['time_str']}]" if seg.get("time_str") else ""
            text = seg.get("text", "")
            body_xml_parts.append(
                f'<w:p><w:pPr><w:spacing w:after="120"/></w:pPr>'
                f'<w:r><w:rPr><w:b/><w:color w:val="18A879"/></w:rPr><w:t>{_escape(speaker)}{_escape(time_str)}: </w:t></w:r>'
                f'<w:r><w:t>{_escape(text)}</w:t></w:r></w:p>'
            )
    else:
        paragraphs = content_text.split("\n\n") if "\n\n" in content_text else content_text.split("\n")
        for p in paragraphs:
            if p.strip():
                body_xml_parts.append(
                    f'<w:p><w:pPr><w:spacing w:after="120"/></w:pPr>'
                    f'<w:r><w:t>{_escape(p.strip())}</w:t></w:r></w:p>'
                )

    document_xml = f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
    <w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
      <w:body>
        {''.join(body_xml_parts)}
      </w:body>
    </w:document>"""

    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", CONTENT_TYPES_XML)
        z.writestr("_rels/.rels", RELS_XML)
        z.writestr("word/_rels/document.xml.rels", WORD_RELS_XML)
        z.writestr("word/styles.xml", STYLES_XML)
        z.writestr("word/document.xml", document_xml)

    return buffer.getvalue()
